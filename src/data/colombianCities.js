// Función helper para buscar ciudad por código
export const getCityByCode = (code) => {
    return colombianCities.find(city => city.code === code);
};

// Función helper para buscar ciudades por departamento
export const getCitiesByDepartment = (department) => {
    return colombianCities.filter(city => city.department === department);
};

// Obtener lista de departamentos únicos
export const getDepartments = () => {
    const departments = [...new Set(colombianCities.map(city => city.department))];
    return departments.sort();
};

// Obtener ciudades ordenadas alfabéticamente
export const getCitiesSorted = () => {
    return [...colombianCities].sort((a, b) => a.name.localeCompare(b.name, 'es'));
};
